"""Embed out/gam.prove.tz in a Coq string (gam_prove_string.v).

Mi-Cho-Coq's parser takes `parameter ...; storage ...; code ...` without the
outer braces octez-client prints, and Coq strings escape " as "".
Usage: python3 -I gen_string.py IN.tz OUT.v
"""
import sys

src = open(sys.argv[1]).read().strip()
if src.startswith("{") and src.endswith("}"):
    src = src[1:-1].strip()
with open(sys.argv[2], "w") as f:
    f.write("(* Generated by gen_string.py from out/gam.prove.tz; do not edit. *)\n")
    f.write("Require Import String.\n\n")
    f.write('Definition gam_prove_s : string := "\n')
    f.write(src.replace('"', '""'))
    f.write('\n".\n')
